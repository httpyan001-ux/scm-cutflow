/* Universal output exporters — Video / Caption(#@) / Script / Timestamps */

export interface ExportBundle {
  faction: string;
  title: string;
  aspect?: string;
  lengthLabel?: string;
  videoName: string;
  caption: string;
  hashtags: string[];
  mentions: string[];
  scriptText: string;
  timestamps: { t: string; label: string }[];
  raw?: Record<string, unknown>;
}

function s(v: unknown): string {
  return typeof v === "string" ? v : "";
}
function arr<T = unknown>(v: unknown): T[] {
  return Array.isArray(v) ? (v as T[]) : [];
}

/** Normalize ANY faction result into a downloadable bundle. */
export function buildBundle(factionName: string, slug: string, result: Record<string, unknown>): ExportBundle {
  const R = result as Record<string, any>;
  const aspect = s(R.aspect) || "16:9";
  const lengthLabel = s(R.length) || s(R.highlightRail) || "";
  const videoName = s(R.download) || `${slug}-output.mp4`;

  /* ---- timestamps ---- */
  const timestamps: { t: string; label: string }[] = [];
  if (Array.isArray(R.timestamps)) {
    for (const x of R.timestamps) timestamps.push({ t: s(x?.t), label: s(x?.label) });
  }
  for (const c of arr<any>(R.chapters)) timestamps.push({ t: s(c?.t), label: s(c?.title) });
  for (const c of arr<string>(R.chapters2)) {
    const m = c.match(/^(\d{1,2}:\d{2})\s+(.*)$/);
    if (m) timestamps.push({ t: m[1], label: m[2] });
    else timestamps.push({ t: "", label: c });
  }
  for (const l of arr<any>(R.lines)) if (l?.t) timestamps.push({ t: s(l.t), label: s(l.mm) || s(l.en) });
  for (const c of arr<any>(R.cuts)) timestamps.push({ t: s(c?.dur), label: `${s(c?.id)} · ${s(c?.hook)}` });
  for (const sl of arr<any>(R.slides)) timestamps.push({ t: `#${sl?.n ?? ""}`, label: s(sl?.title) });

  /* ---- script ---- */
  let scriptText = s(R.scriptText);
  if (!scriptText) {
    const parts: string[] = [];
    for (const x of arr<string>(R.script)) parts.push(x);
    for (const x of arr<string>(R.summary)) parts.push(`• ${x}`);
    for (const x of arr<string>(R.bullets)) parts.push(`• ${x}`);
    for (const l of arr<any>(R.lines)) parts.push(`[${s(l?.t)}] ${s(l?.mm)}${l?.en ? `\n    ${s(l.en)}` : ""}`);
    for (const q of arr<any>(R.qa)) parts.push(`Q: ${s(q?.q)}\nA: ${s(q?.a)}`);
    if (s(R.transcript)) parts.push(s(R.transcript));
    scriptText = parts.join("\n\n");
  }

  /* ---- caption + #@ ---- */
  let caption = s(R.caption);
  let hashtags = arr<string>(R.hashtags);
  let mentions = arr<string>(R.mentions);
  if (!hashtags.length) {
    const base = ["scmcutflow", slug.replace(/-/g, ""), "myanmar", "viral", "fyp"];
    const extra = arr<string>(R.entities).slice(0, 3).map((e) => e.replace(/[^a-zA-Z0-9\u1000-\u109F]/g, "").slice(0, 18)).filter(Boolean);
    hashtags = Array.from(new Set([...base, ...extra])).map((h) => `#${h}`);
  }
  if (!mentions.length) mentions = ["@scm.cutflow"];
  if (!caption) {
    const head = s(R.headline) || s(R.prompt) || `${factionName} output`;
    const first = arr<string>(R.summary)[0] || arr<string>(R.bullets)[0] || s(R.polish) || s(R.stats) || "";
    caption = [`🎬 ${head}`, first ? `\n${first}` : "", "", hashtags.join(" "), mentions.join(" ")].filter(Boolean).join("\n");
  }

  return {
    faction: factionName,
    title: s(R.myTitle) || s(R.headline) || s(R.prompt) || factionName,
    aspect,
    lengthLabel,
    videoName,
    caption,
    hashtags,
    mentions,
    scriptText,
    timestamps: timestamps.filter((x) => x.label),
    raw: result,
  };
}

const LINE = "═".repeat(46);

export function captionTxt(b: ExportBundle): string {
  return [
    `${LINE}\n  ${b.faction} · CAPTION PACK\n${LINE}`,
    b.caption,
    "",
    `${LINE}\nHASHTAGS\n${LINE}`,
    b.hashtags.join(" "),
    "",
    `${LINE}\nMENTIONS\n${LINE}`,
    b.mentions.join(" "),
    "",
    `generated by SCM CUTFLOW · ${new Date().toLocaleString()}`,
  ].join("\n");
}

export function scriptTxt(b: ExportBundle): string {
  return [
    `${LINE}\n  ${b.faction} · SCRIPT\n  ${b.title}\n${LINE}`,
    b.scriptText || "(no script)",
    "",
    `generated by SCM CUTFLOW · ${new Date().toLocaleString()}`,
  ].join("\n");
}

export function timestampTxt(b: ExportBundle): string {
  return [
    `${LINE}\n  ${b.faction} · TIMESTAMPS\n${LINE}`,
    ...b.timestamps.map((x) => `${(x.t || "--:--").padEnd(10)} ${x.label}`),
    "",
    `generated by SCM CUTFLOW · ${new Date().toLocaleString()}`,
  ].join("\n");
}

/** FULL package: video ref + caption #@ + timestamps + script in one .txt */
export function fullTxt(b: ExportBundle): string {
  return [
    LINE,
    `  SCM CUTFLOW — ${b.faction} OUTPUT PACKAGE`,
    `  ${b.title}`,
    LINE,
    "",
    `VIDEO FILE : ${b.videoName}`,
    `ASPECT     : ${b.aspect}`,
    b.lengthLabel ? `LENGTH     : ${b.lengthLabel}` : "",
    `EXPORTED   : ${new Date().toLocaleString()}`,
    "",
    `${LINE}\n[1] CAPTION (#@)\n${LINE}`,
    b.caption,
    "",
    `HASHTAGS : ${b.hashtags.join(" ")}`,
    `MENTIONS : ${b.mentions.join(" ")}`,
    "",
    `${LINE}\n[2] TIMESTAMPS\n${LINE}`,
    ...(b.timestamps.length ? b.timestamps.map((x) => `${(x.t || "--:--").padEnd(10)} ${x.label}`) : ["(none)"]),
    "",
    `${LINE}\n[3] SCRIPT\n${LINE}`,
    b.scriptText || "(no script)",
    "",
    LINE,
    "  generated by SCM CUTFLOW · AETHER-FORGE",
    LINE,
  ].filter((x) => x !== "").join("\n");
}

export function srtFrom(b: ExportBundle): string {
  const toSrt = (mmss: string, add = 0) => {
    const [m, s2] = (mmss || "00:00").split(":").map((n) => parseInt(n, 10) || 0);
    const total = m * 60 + s2 + add;
    const hh = String(Math.floor(total / 3600)).padStart(2, "0");
    const mm = String(Math.floor((total % 3600) / 60)).padStart(2, "0");
    const ss = String(total % 60).padStart(2, "0");
    return `${hh}:${mm}:${ss},000`;
  };
  return b.timestamps
    .map((x, i) => `${i + 1}\n${toSrt(x.t)} --> ${toSrt(x.t, 4)}\n${x.label}\n`)
    .join("\n");
}

export function downloadText(filename: string, text: string) {
  const blob = new Blob([text], { type: "text/plain;charset=utf-8" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 2000);
}

export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    try {
      const ta = document.createElement("textarea");
      ta.value = text;
      ta.style.position = "fixed";
      ta.style.opacity = "0";
      document.body.appendChild(ta);
      ta.select();
      const ok = document.execCommand("copy");
      document.body.removeChild(ta);
      return ok;
    } catch {
      return false;
    }
  }
}
